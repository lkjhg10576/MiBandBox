function classify(raw) {
  const name = String(raw || '').trim()
  if (!name) return null
  if (items[name]) return { key: items[name], name, ...categories[items[name]] }
  let hit = null
  Object.keys(items).forEach((key) => {
    if (name.indexOf(key) !== -1 || key.indexOf(name) !== -1) {
      if (!hit || key.length > hit.length) hit = key
    }
  })
  if (hit) return { key: items[hit], name, ...categories[items[hit]] }
  return null
}

