function keyOf(month, day) {
  const m = Number(month)
  const d = Number(day)
  return (m < 10 ? '0' + m : '' + m) + '-' + (d < 10 ? '0' + d : '' + d)
}

/** 归一化一条史实：旧的字符串写法也转成同样的结构 */
function normalizeItem(v) {
  if (!v) return null
  if (typeof v === 'string') {
    const y = v.match(/(\d{4})/)
    return { year: y ? Number(y[1]) : 0, title: '', text: v, tag: '' }
  }
  if (typeof v === 'object') {
    return {
      year: Number(v.year) || 0,
      title: String(v.title || ''),
      text: String(v.text || ''),
      tag: String(v.tag || '')
    }
  }
  return null
}

/** 取某天的史实条目数组（没有则空数组） */
function getByDate(month, day) {
  const raw2 = events[keyOf(month, day)]
  if (!raw2) return []
  const list = Array.isArray(raw2) ? raw2 : [raw2]
  const out = []
  for (let i = 0; i < list.length; i++) {
    const it = normalizeItem(list[i])
    if (it && it.text) out.push(it)
  }
  return out
}

/** 稳定散列：同一 (month, day) 永远得到同一组小知识 */
function hashOf(month, day) {
  let h = (Number(month) * 73856093) ^ (Number(day) * 19349663)
  h = Math.imul(h ^ (h >>> 13), 0x5bd1e995)
  return (h ^ (h >>> 15)) >>> 0
}

/** 当天的两条小知识（互不相同） */
function tipOfDay(month, day) {
  const n = tips.length
  if (!n) return []
  const h = hashOf(month, day)
  const i1 = h % n
  let i2 = Math.floor(h / n) % n
  if (i2 === i1) i2 = (i2 + 1) % n
  return [tips[i1], tips[i2]]
}

